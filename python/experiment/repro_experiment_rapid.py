x = np.arange(0, 50.0, 0.1)
y = np.arange(0, 50.0, 0.1)
X, Y = np.meshgrid(x, y)
inside = ~((X > 30.0) & (Y > 30.0))


def reconstruct(di, betas):
    P = np.zeros((500, 500))
    k = 0
    for s in R:
        for t in T:
            b = betas[k]
            k += 1
            a = np.array(t, float)
            c = np.array(s, float)
            blocked = ((np.linspace(a[0], c[0], 400) > 30.01) &
                       (np.linspace(a[1], c[1], 400) > 30.01)).any()
            if blocked:
                continue
            d = np.hypot(*(c - a))
            rd = (np.hypot(X - a[0], Y - a[1]) + np.hypot(X - c[0], Y - c[1])) / d
            w = np.where(rd < b, (b - rd) / (b - 1.0), 0.0)
            P += di[k - 1] * w * inside
    P2 = P.copy()
    P2[:100, :] = 0
    P2[:, :100] = 0
    P2[401:, :] = 0
    P2[:, 401:] = 0
    P2 *= inside
    r, c = np.unravel_index(np.argmax(P2), P2.shape)
    return x[c] * 10, y[r] * 10, (x[c] * 10, y[r] * 10)


